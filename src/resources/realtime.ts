/**
 * Realtime API resource — WebSocket voice/chat sessions plus the telephony
 * calls API.
 *
 * Raw audio in both directions (`pcm16` @ 24 kHz by default, or G.711) over
 * binary frames or base64 JSON events, server turn detection (Silero VAD +
 * Smart Turn, `semantic_vad` by default; `turn_detection: null` = manual
 * commit), streamed PCM output, barge-in, first messages and per-turn latency
 * metrics.
 *
 * Works with the browser's native `WebSocket`, Node.js >= 22 (global
 * `WebSocket`), Bun, or any compatible implementation (e.g. the `ws` package)
 * passed via `connect({ webSocket })`.
 */

