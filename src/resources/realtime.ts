/** Structural subset shared by browser WebSocket, Node global, and `ws`. */
export interface WebSocketLike {
  readyState: number;
  /** Switched from `blob` to `arraybuffer` when present, so binary audio frames decode synchronously. */
  binaryType?: string;
  send(data: string | ArrayBufferLike | ArrayBufferView): void;
  close(code?: number, reason?: string): void;
  addEventListener(type: 'open', listener: () => void): void;
  addEventListener(type: 'close', listener: (event: { code: number; reason: string }) => void): void;
  addEventListener(type: 'error', listener: (event: unknown) => void): void;
  addEventListener(type: 'message', listener: (event: { data: unknown }) => void): void;
}

/**
 * A WebSocket constructor. Header-capable implementations (`ws`, Node >= 22,
 * Bun) are called as `new WebSocket(url, { headers })`; others as `new WebSocket(url)`.
 */
// eslint-disable-next-line @typescript-eslint/no-explicit-any
export type WebSocketConstructorLike = new (url: string, ...args: any[]) => WebSocketLike;

/**
 * How `connect()` sends the API key.
 *
 * - `auto` (default): `Authorization: Bearer` header when the WebSocket
 *   implementation can set upgrade headers (the `ws` package, Node >= 22's
 *   global `WebSocket`, Bun), otherwise `?api_key=` (browsers).
 * - `header` / `query`: force one.
 *
 * The server only accepts `?api_key=` for tokens scoped to the realtime
 * service (a URL leaks more easily than a header); full-scope tokens must use
 * the header.
 */
export type RealtimeAuthMode = 'auto' | 'header' | 'query';

export interface RealtimeConnectOptions {
  /**
   * Realtime model or chat model key. The response generator is a
   * session-start choice — it may alternatively be set via `updateSession`
   * before the first response, but locks once the conversation starts.
   */
  model?: string;
  /** Agent key — responses are generated by this agent instead of a raw model. Locked like `model`. */
  agent?: string;
  /**
   * Initial session config. Sent as ONE `session.update` right after the
   * socket opens, merged with `runtimeContext` / `variables` /
   * `firstSpeaker` / `firstMessage` — so a `first_speaker: 'agent'` greeting
   * already sees all of them.
   */
  session?: RealtimeSessionUpdate;
  /**
   * Downstream auth/data for agent tool calls — sent in the initial
   * `session.update`. Also settable/refreshable later via
   * `updateSession({ runtime_context })`.
   */
  runtimeContext?: RuntimeContext;
  /** `{{name}}` template variables (instructions, first message; forwarded to agents). */
  variables?: RealtimeVariables;
  /** Who speaks first. `agent` starts the first message as soon as the initial `session.update` is applied. */
  firstSpeaker?: RealtimeFirstSpeaker;
  /** What the agent says first (overrides the preset). */
  firstMessage?: RealtimeFirstMessage;
  /** How the API key is sent (default `auto`). */
  auth?: RealtimeAuthMode;
  /**
   * Extra upgrade headers, e.g. `X-Cpr-Hdr-*` runtime-context headers.
   * Header-capable WebSocket implementations only (throws otherwise).
   */
  headers?: Record<string, string>;
  /** Custom WebSocket implementation (defaults to the global `WebSocket`). */
  webSocket?: WebSocketConstructorLike;
  /**
   * Give up when the session is not ready this long after `connect()` was
   * called (default 30000; `0` = wait forever). The clock covers the socket
   * opening and the server creating the session.
   */
  timeoutMs?: number;
}

