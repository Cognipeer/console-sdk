export class RealtimeResource {
  private baseURL: string;
  private apiKey: string;

  /** Realtime model presets (CRUD). */
  public models: RealtimeModelsResource;

  /** Telephony calls (outbound dial, status, hang up). */
  public calls: RealtimeCallsResource;

  constructor(baseURL: string, apiKey: string, http: HttpClient) {
    this.baseURL = baseURL;
    this.apiKey = apiKey;
    this.models = new RealtimeModelsResource(http);
    this.calls = new RealtimeCallsResource(http);
  }

  /** Build the websocket URL (useful for custom clients). */
  url(options?: RealtimeUrlOptions): string {
    const params = new URLSearchParams();
    if (options?.includeApiKey !== false) params.set('api_key', this.apiKey);
    if (options?.model) params.set('model', options.model);
    if (options?.agent) params.set('agent', options.agent);
    if (options?.firstSpeaker) params.set('first_speaker', options.firstSpeaker);
    if (options?.variables) params.set('variables', JSON.stringify(options.variables));
    const query = params.toString();
    return `${this.wsBase()}/api/client/v1/realtime${query ? `?${query}` : ''}`;
  }

  private wsBase(): string {
    return this.baseURL.replace(/^http/i, 'ws');
  }

  /**
   * Open a realtime session. Resolves once the server has created the session
   * (`session.created`), not when the socket opens: the server accepts the
   * upgrade first and checks the key, the preset and the agent afterwards. A
   * refused session — invalid or unscoped key, disabled preset, unknown agent
   * — rejects with the server's reason, as does a connection that fails or is
   * not ready within `timeoutMs`.
   */
  async connect(options?: RealtimeConnectOptions): Promise<RealtimeConnection> {
    const globalCtor = (globalThis as { WebSocket?: WebSocketConstructorLike }).WebSocket;
    const Ctor = options?.webSocket ?? globalCtor;
    if (!Ctor) {
      throw new Error(
        'No WebSocket implementation found. Pass one via connect({ webSocket }), e.g. `import WebSocket from "ws"`.',
      );
    }
    const mode = options?.auth ?? 'auto';
    const viaHeader = mode === 'header' || (mode === 'auto' && canSetUpgradeHeaders(Ctor, globalCtor));
    if (options?.headers && !viaHeader) {
      throw new Error(
        'connect({ headers }) needs a WebSocket implementation that can set upgrade headers (e.g. the `ws` package).',
      );
    }
    const url = this.url({ model: options?.model, agent: options?.agent, includeApiKey: !viaHeader });
    const socket = viaHeader
      ? new Ctor(url, { headers: { ...options?.headers, Authorization: `Bearer ${this.apiKey}` } })
      : new Ctor(url);
    // Listen before the socket opens so `session.created` is never missed.
    const connection = new RealtimeConnection(socket);
    await awaitSession(socket, connection, options);
    return connection;
  }
}

/**
 * Wait for the server to accept the session. The initial `session.update`
 * goes out as soon as the socket opens: the server holds early messages while
 * it authenticates and replays them in order, so a greeting still starts from
 * it. Anything that ends the connection before `session.created` — an `error`
 * event (always followed by a close), a close, a transport error, the timeout —
 * rejects, and the socket is closed.
 */
function awaitSession(
  socket: WebSocketLike,
  connection: RealtimeConnection,
  options: RealtimeConnectOptions | undefined,
): Promise<void> {
  const timeoutMs = options?.timeoutMs ?? DEFAULT_CONNECT_TIMEOUT_MS;
  return new Promise<void>((resolve, reject) => {
    const offs: Array<() => void> = [];
    let timer: ReturnType<typeof setTimeout> | undefined;
    let opened = false;
    let settled = false;
    const settle = (error?: Error) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      offs.forEach((off) => off());
      if (!error) {
        resolve();
        return;
      }
      connection.close();
      reject(error);
    };

    if (Number.isFinite(timeoutMs) && timeoutMs > 0) {
      timer = setTimeout(() => {
        settle(new Error(
          `Realtime session not ready after ${timeoutMs} ms (${opened ? 'the socket is open, the server has not created the session' : 'the socket did not open'})`,
        ));
      }, timeoutMs);
    }
    socket.addEventListener('open', () => {
      opened = true;
      try {
        const initial = initialSessionUpdate(options);
        if (initial) connection.updateSession(initial);
      } catch (error) {
        settle(error instanceof Error ? error : new Error(String(error)));
      }
    });
    socket.addEventListener('error', (event: unknown) => settle(toSocketError(event, 'WebSocket connection failed')));
    offs.push(connection.onClose((info) => settle(new Error(
      opened
        ? `WebSocket closed before the session was created (${describeClose(info)})`
        : `WebSocket closed before opening (code ${info.code})`,
    ))));
    offs.push(connection.on('error', (event) => {
      const { message, code } = event.error ?? {};
      settle(new Error(`Realtime connection refused: ${message ?? 'unknown error'}${code ? ` (${code})` : ''}`));
    }));
    offs.push(connection.on('session.created', () => settle()));
  });
}

/** Merge the connect-time session options into one `session.update` (or none). */
function initialSessionUpdate(options?: RealtimeConnectOptions): RealtimeSessionUpdate | null {
  if (!options) return null;
  const session: RealtimeSessionUpdate = { ...options.session };
  if (options.runtimeContext) session.runtime_context = options.runtimeContext;
  if (options.variables) session.variables = { ...session.variables, ...options.variables };
  if (options.firstSpeaker) session.first_speaker = options.firstSpeaker;
  if (options.firstMessage) session.first_message = options.firstMessage;
  return Object.keys(session).length > 0 ? session : null;
}

/** Error behind a socket `error` event: an Error as is, the one a `ws` ErrorEvent wraps, else `fallback`. */
function toSocketError(event: unknown, fallback: string): Error {
  if (event instanceof Error) return event;
  const detail = event as { error?: unknown; message?: unknown } | null | undefined;
  if (detail?.error instanceof Error) return detail.error;
  return new Error(typeof detail?.message === 'string' && detail.message ? detail.message : fallback);
}

/** `code 4401: Unauthorized` — a close code with its reason and the transport error that came with it. */
function describeClose(info: RealtimeCloseInfo): string {
  return `code ${info.code}${info.reason ? `: ${info.reason}` : ''}${info.error ? `; ${info.error.message}` : ''}`;
}

/**
 * Whether `new Ctor(url, { headers })` sends the headers: the `ws` package,
 * Bun's and Node >= 22's global `WebSocket` (undici's init dictionary).
 * Browsers cannot set upgrade headers.
 *
 * `ws` is recognised by its shape, in either module system. Only the
 * CommonJS entry (`ws/index.js`) attaches the `Receiver` / `Sender` statics;
 * an ES-module import resolves to `ws/wrapper.mjs`, whose default export is the
 * bare class without them. What every `ws` socket has — and browser and undici
 * sockets lack — is `terminate()`.
 */
function canSetUpgradeHeaders(
  Ctor: WebSocketConstructorLike,
  globalCtor: WebSocketConstructorLike | undefined,
): boolean {
  const statics = Ctor as unknown as Record<string, unknown>;
  if (typeof statics.Receiver === 'function' && typeof statics.Sender === 'function') return true;
  if (typeof (Ctor.prototype as { terminate?: unknown } | undefined)?.terminate === 'function') return true;
  if (Ctor !== globalCtor) return false;
  const versions = (globalThis as { process?: { versions?: Record<string, string | undefined> } }).process?.versions;
  if (!versions || versions.deno) return false;
  if (versions.bun) return true;
  const major = Number(versions.node?.split('.')[0]);
  return Number.isFinite(major) && major >= 22;
}

// ── Audio helpers ─────────────────────────────────────────────────────

const LITTLE_ENDIAN = new Uint8Array(new Uint16Array([1]).buffer)[0] === 1;

/**
 * Convert Web Audio samples (Float32, -1..1) to 16-bit PCM — what
 * `sendAudio()` does with a `Float32Array`.
 */
export function float32ToPcm16(samples: Float32Array): Int16Array {
  const out = new Int16Array(samples.length);
  for (let i = 0; i < samples.length; i++) {
    const s = Math.max(-1, Math.min(1, samples[i]));
    out[i] = s < 0 ? Math.round(s * 0x8000) : Math.round(s * 0x7fff);
  }
  return out;
}

/** Convert 16-bit PCM (e.g. `chunk.pcm` from `onAudio`) to Float32 samples for Web Audio playback. */
export function pcm16ToFloat32(pcm: Int16Array): Float32Array {
  const out = new Float32Array(pcm.length);
  for (let i = 0; i < pcm.length; i++) out[i] = pcm[i] / (pcm[i] < 0 ? 0x8000 : 0x7fff);
  return out;
}

/** Raw bytes for any accepted audio input; Int16 as s16le, Float32 converted to pcm16. */
function audioBytes(audio: ArrayBuffer | ArrayBufferView): Uint8Array {
  if (!ArrayBuffer.isView(audio)) return new Uint8Array(audio);
  if (audio instanceof Float32Array) return int16Bytes(float32ToPcm16(audio));
  if (audio instanceof Int16Array) return int16Bytes(audio);
  if (audio instanceof Uint8Array) return audio;
  return new Uint8Array(audio.buffer, audio.byteOffset, audio.byteLength);
}

function int16Bytes(pcm: Int16Array): Uint8Array {
  if (LITTLE_ENDIAN) return new Uint8Array(pcm.buffer, pcm.byteOffset, pcm.byteLength);
  const out = new Uint8Array(pcm.length * 2);
  const view = new DataView(out.buffer);
  for (let i = 0; i < pcm.length; i++) view.setInt16(i * 2, pcm[i], true);
  return out;
}

/** s16le bytes → samples (an odd trailing byte is dropped). */
function pcm16FromBytes(bytes: Uint8Array): Int16Array {
  const count = bytes.byteLength >> 1;
  if (LITTLE_ENDIAN && bytes.byteOffset % 2 === 0) {
    // Copy so the samples never alias a pooled Buffer.
    return new Int16Array(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + count * 2));
  }
  const out = new Int16Array(count);
  const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
  for (let i = 0; i < count; i++) out[i] = view.getInt16(i * 2, true);
  return out;
}

let ulawTable: Int16Array | null = null;
let alawTable: Int16Array | null = null;

/** ITU-T G.711 μ-law byte → linear sample. */
function ulawToLinear(value: number): number {
  const u = ~value & 0xff;
  const magnitude = ((((u & 0x0f) << 3) + 0x84) << ((u >> 4) & 0x07)) - 0x84;
  return u & 0x80 ? -magnitude : magnitude;
}

/** ITU-T G.711 A-law byte → linear sample. */
function alawToLinear(value: number): number {
  const a = value ^ 0x55;
  const exponent = (a >> 4) & 0x07;
  const mantissa = a & 0x0f;
  const magnitude = exponent === 0 ? (mantissa << 4) + 8 : ((mantissa << 4) + 0x108) << (exponent - 1);
  return a & 0x80 ? magnitude : -magnitude;
}

function g711Decode(bytes: Uint8Array, law: 'ulaw' | 'alaw'): Int16Array {
  let table = law === 'ulaw' ? ulawTable : alawTable;
  if (!table) {
    table = new Int16Array(256);
    for (let i = 0; i < 256; i++) table[i] = law === 'ulaw' ? ulawToLinear(i) : alawToLinear(i);
    if (law === 'ulaw') ulawTable = table;
    else alawTable = table;
  }
  const out = new Int16Array(bytes.length);
  for (let i = 0; i < bytes.length; i++) out[i] = table[bytes[i]];
  return out;
}

function decodePcm(format: RealtimeAudioFormat, bytes: Uint8Array): Int16Array {
  if (format === 'g711_ulaw') return g711Decode(bytes, 'ulaw');
  if (format === 'g711_alaw') return g711Decode(bytes, 'alaw');
  return pcm16FromBytes(bytes);
}

function defaultSampleRate(format: RealtimeAudioFormat): number {
  return format === 'pcm16' ? 24000 : 8000;
}

/** MIME type of a frame — the same strings the server sends as `content_type`. */
function contentTypeFor(format: RealtimeAudioFormat, sampleRate: number): string {
  if (format === 'g711_ulaw') return 'audio/PCMU;rate=8000';
  if (format === 'g711_alaw') return 'audio/PCMA;rate=8000';
  return `audio/L16;rate=${sampleRate}`;
}

// ── Frame/byte helpers ───────────────────────────────────────────────

interface BlobLike {
  arrayBuffer(): Promise<ArrayBuffer>;
}

function isBlobLike(data: unknown): data is BlobLike {
  return typeof data === 'object' && data !== null && !ArrayBuffer.isView(data)
    && typeof (data as { arrayBuffer?: unknown }).arrayBuffer === 'function';
}

/** Binary frame payload as bytes: ArrayBuffer, any view (Node Buffer), or `ws` fragments. */
function frameBytes(data: unknown): Uint8Array | null {
  if (data instanceof Uint8Array) return data;
  if (ArrayBuffer.isView(data)) return new Uint8Array(data.buffer, data.byteOffset, data.byteLength);
  if (data instanceof ArrayBuffer) return new Uint8Array(data);
  if (Array.isArray(data) && data.length > 0 && data.every((part) => part instanceof Uint8Array)) {
    return concatBytes(data as Uint8Array[]);
  }
  return null;
}

/** `{ … }` — cheap pre-check before trying to read bytes as a JSON event. */
function looksLikeJsonObject(bytes: Uint8Array): boolean {
  return bytes.length >= 2 && bytes[0] === 0x7b && bytes[bytes.length - 1] === 0x7d;
}

function utf8Decode(bytes: Uint8Array): string {
  const globals = globalThis as {
    TextDecoder?: new () => { decode(input: Uint8Array): string };
    Buffer?: { from(data: Uint8Array): { toString(encoding: string): string } };
  };
  if (globals.TextDecoder) return new globals.TextDecoder().decode(bytes);
  if (globals.Buffer) return globals.Buffer.from(bytes).toString('utf8');
  return String.fromCharCode(...bytes);
}

function concatBytes(parts: Uint8Array[]): Uint8Array {
  const out = new Uint8Array(parts.reduce((sum, part) => sum + part.byteLength, 0));
  let offset = 0;
  for (const part of parts) {
    out.set(part, offset);
    offset += part.byteLength;
  }
  return out;
}

function bytesToBase64(bytes: Uint8Array): string {
  const globals = globalThis as {
    Buffer?: { from(data: Uint8Array): { toString(encoding: string): string } };
    btoa?: (data: string) => string;
  };
  if (globals.Buffer) {
    return globals.Buffer.from(bytes).toString('base64');
  }
  let binary = '';
  for (let i = 0; i < bytes.length; i++) binary += String.fromCharCode(bytes[i]);
  if (!globals.btoa) throw new Error('No base64 encoder available');
  return globals.btoa(binary);
}

function base64ToBytes(base64: string): Uint8Array {
  const globals = globalThis as {
    Buffer?: { from(data: string, encoding: string): Uint8Array };
    atob?: (data: string) => string;
  };
  if (globals.Buffer) {
    const buf = globals.Buffer.from(base64, 'base64');
    return new Uint8Array(buf.buffer, buf.byteOffset, buf.byteLength);
  }
  if (!globals.atob) throw new Error('No base64 decoder available');
  const binary = globals.atob(base64);
  const out = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) out[i] = binary.charCodeAt(i);
  return out;
}
