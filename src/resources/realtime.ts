type AnyListener = (event: RealtimeServerEvent) => void;

const OPEN = 1;

/** `connect()` gives up after this long without a ready session. */
const DEFAULT_CONNECT_TIMEOUT_MS = 30_000;

/** Responses whose output format is remembered for attributing binary frames (oldest dropped first). */
const MAX_TRACKED_RESPONSES = 16;

/**
 * Server errors raised by audio input, speech output or other events — never
 * by a `response.create`, so they must not fail a pending `respond()`:
 * `tts_failed` leaves the response running and completing; `forbidden` is a
 * `session.update` refused (like `generator_locked`). (`event_too_large` is
 * not listed: an oversized `response.create { input }` is the one request it
 * can be about, and nothing else will answer it.)
 */
const UNRELATED_ERROR_CODES = new Set([
  'invalid_audio',
  'invalid_audio_format',
  'audio_buffer_full',
  'audio_buffer_empty',
  'transcription_failed',
  'tts_failed',
  'invalid_item',
  'generator_locked',
  'forbidden',
  'unknown_event',
  'invalid_json',
]);

/** Wire audio formats (input and output). */
const AUDIO_FORMATS = new Set<string>(['pcm16', 'g711_ulaw', 'g711_alaw']);

function asAudioFormat(value: unknown): RealtimeAudioFormat | null {
  return typeof value === 'string' && AUDIO_FORMATS.has(value) ? (value as RealtimeAudioFormat) : null;
}

/**
 * A live realtime connection. Listen with `on(type, cb)` (use `'*'` for all
 * events), consume audio with `onAudio(cb)`, stream microphone audio with
 * `sendAudio(bytes)`, or use the high-level `respond()` helper for simple
 * turn-taking.
 */
export class RealtimeConnection {
  private socket: WebSocketLike;
  private listeners = new Map<string, Set<AnyListener>>();
  private audioListeners = new Set<RealtimeAudioListener>();
  /** Latest session echoed by the server (`session.created` / `session.updated`). */
  private serverSession: RealtimeSessionView | null = null;
  /** Audio settings this client asked for — used until the server echoes its own. */
  private requested: { output?: RealtimeAudioFormat; outputRate?: number } = {};
  /** Responses created and not yet done. */
  private openResponses = new Set<string>();
  /** Response the next binary audio frame belongs to (binary frames carry no id). */
  private audioResponseId: string | null = null;
  /**
   * Output format and rate each response started with. The server fixes them
   * when a response starts and binary frames do not say, so a mid-response
   * `session.update` must not relabel the frames still on the wire.
   */
  private responseAudio = new Map<string, { format: RealtimeAudioFormat; sampleRate: number }>();
  /** Sentence announced by `response.audio_transcript.delta`, attached to the next binary frame. */
  private pendingAudioText: string | undefined;
  /** Non-null while a Blob frame is being read; later frames queue behind it to keep their order. */
  private inbox: Promise<void> | null = null;
  private inboxDepth = 0;
  /** Set (briefly) by {@link holdFrames}; frames queue until it settles. */
  private held: Promise<void> | null = null;
  /** Set once the socket closed — by the server, the network or {@link close}. */
  private closeInfo: RealtimeCloseInfo | null = null;
  private closeListeners = new Set<RealtimeCloseListener>();
  /** Calls that can no longer finish once the socket is gone (`respond()`); each rejects its caller. */
  private waiters = new Set<(error: Error) => void>();
  /** Last transport error, reported with the close that follows it. */
  private socketError: Error | undefined;

  constructor(socket: WebSocketLike) {
    this.socket = socket;
    // Browsers and undici deliver binary frames as Blob by default, which can
    // only be read asynchronously — ArrayBuffer keeps audio in event order.
    if (socket.binaryType === 'blob') socket.binaryType = 'arraybuffer';
    socket.addEventListener('message', (event: { data: unknown }) => this.receive(event.data));
    socket.addEventListener('error', (event: unknown) => {
      this.socketError = toSocketError(event, 'WebSocket error');
    });
    socket.addEventListener('close', (event: { code: number; reason: string }) => this.handleClose(event));
  }

  /** Latest session config echoed by the server, or `null` before `session.created`. */
  get session(): RealtimeSessionView | null {
    return this.serverSession;
  }

  /** `null` while the connection is open; how it ended once it closed (see {@link onClose}). */
  get closed(): RealtimeCloseInfo | null {
    return this.closeInfo;
  }

  /**
   * Be told when the connection ends — the server closed it (`4401`
   * unauthorized, `4402` license required, `1013` server busy, `1009` too
   * much data, `1011` server error…), the network
   * dropped, or {@link close} was called. Calls to {@link respond} still
   * pending at that point reject. Returns an unsubscribe function. A listener
   * added after the close is called right away (asynchronously).
   */
  onClose(listener: RealtimeCloseListener): () => void {
    const info = this.closeInfo;
    if (info) {
      let active = true;
      void Promise.resolve().then(() => {
        if (active) listener(info);
      });
      return () => {
        active = false;
      };
    }
    this.closeListeners.add(listener);
    return () => {
      this.closeListeners.delete(listener);
    };
  }

  private handleClose(event: { code: number; reason: string } | undefined): void {
    if (this.closeInfo) return;
    const info: RealtimeCloseInfo = {
      code: typeof event?.code === 'number' ? event.code : 1005,
      reason: typeof event?.reason === 'string' ? event.reason : '',
      ...(this.socketError ? { error: this.socketError } : {}),
    };
    this.closeInfo = info;
    this.failWaiters(new Error(`Realtime socket closed (${describeClose(info)})`));
    const listeners = [...this.closeListeners];
    this.closeListeners.clear();
    for (const listener of listeners) listener(info);
  }

  /** Reject whatever is waiting on this connection (the socket is gone, so nothing will answer). */
  private failWaiters(error: Error): void {
    const waiters = [...this.waiters];
    this.waiters.clear();
    for (const fail of waiters) fail(error);
  }

  /** Subscribe to a server event type, or `'*'` for every event. Returns an unsubscribe function. */
  on<K extends keyof RealtimeServerEventMap>(type: K, listener: (event: RealtimeServerEventMap[K]) => void): () => void;
  on(type: string, listener: (event: RealtimeServerEvent) => void): () => void;
  on(type: string, listener: (event: never) => void): () => void {
    const set = this.listeners.get(type) ?? new Set<AnyListener>();
    const stored = listener as unknown as AnyListener;
    set.add(stored);
    this.listeners.set(type, set);
    return () => set.delete(stored);
  }

  off(type: string, listener: (event: never) => void): void {
    this.listeners.get(type)?.delete(listener as unknown as AnyListener);
  }

  /**
   * Subscribe to response audio from either transport — JSON
   * `response.audio.delta` or binary frames (`audio_transport: 'binary'`).
   * Every chunk carries the raw `bytes` and decoded `pcm` samples (Int16,
   * mono, `sampleRate`; G.711 is decoded too). On
   * `output_audio_buffer.cleared`, flush whatever playback is queued.
   */
  onAudio(listener: RealtimeAudioListener): () => void {
    this.audioListeners.add(listener);
    return () => this.audioListeners.delete(listener);
  }

  private dispatch(event: RealtimeServerEvent): void {
    for (const listener of this.listeners.get(event.type) ?? []) listener(event);
    for (const listener of this.listeners.get('*') ?? []) listener(event);
  }

  private emitAudio(chunk: RealtimeAudioChunk): void {
    for (const listener of this.audioListeners) listener(chunk);
  }

  // ── Inbound frames ──────────────────────────────────────────────────

  private receive(data: unknown): void {
    if (this.inboxDepth === 0 && !this.held && !isBlobLike(data)) {
      this.handleFrame(data);
      return;
    }
    this.inboxDepth++;
    this.inbox = (this.inbox ?? Promise.resolve())
      .then(async () => {
        await this.held;
        this.handleFrame(isBlobLike(data) ? new Uint8Array(await data.arrayBuffer()) : data);
      })
      .catch(() => undefined)
      .then(() => {
        if (--this.inboxDepth === 0) this.inbox = null;
      });
  }

  /**
   * Make the frames that follow wait until the current task is over.
   * `connect()` resolves while `session.created` is being dispatched, and its
   * caller only attaches listeners once the `await` continues — but one socket
   * read can carry more frames than that one: the echo of the initial
   * `session.update`, a text greeting. Dispatched on the spot they would reach
   * nobody; queued, they arrive in order right after the caller has had its turn.
   */
  private holdFrames(): void {
    if (this.held) return;
    const held: Promise<void> = new Promise<void>((resolve) => setTimeout(resolve, 0)).then(() => {
      if (this.held === held) this.held = null;
    });
    this.held = held;
  }

  private handleFrame(data: unknown): void {
    if (typeof data === 'string') {
      this.handleText(data, false);
      return;
    }
    const bytes = frameBytes(data);
    if (!bytes) {
      this.handleText(String(data), false);
      return;
    }
    // Some WebSocket implementations hand text frames over as bytes too.
    if (looksLikeJsonObject(bytes) && this.handleText(utf8Decode(bytes), true)) return;
    this.handleBinaryAudio(bytes);
  }

  /** Parse and dispatch one JSON event. `strict` = only accept a `{ type }` object (bytes that may be audio). */
  private handleText(text: string, strict: boolean): boolean {
    let parsed: RealtimeServerEvent;
    try {
      parsed = JSON.parse(text) as RealtimeServerEvent;
    } catch {
      return false;
    }
    if (!parsed || typeof parsed !== 'object') return false;
    if (strict && typeof parsed.type !== 'string') return false;
    this.track(parsed);
    this.dispatch(parsed);
    if (parsed.type === 'response.audio.delta') this.handleAudioDelta(parsed);
    if (parsed.type === 'session.created') this.holdFrames();
    return true;
  }

  /** Bookkeeping that keeps binary frames attributable and audio formats known. */
  private track(event: RealtimeServerEvent): void {
    switch (event.type) {
      case 'session.created':
      case 'session.updated':
        if (event.session && typeof event.session === 'object') {
          this.serverSession = event.session as RealtimeSessionView;
        }
        break;
      case 'response.created': {
        const id = (event.response as { id?: unknown } | undefined)?.id;
        if (typeof id === 'string') {
          this.openResponses.add(id);
          this.audioResponseId = id;
          this.pendingAudioText = undefined;
          this.rememberOutputAudio(id);
        }
        break;
      }
      case 'response.audio_transcript.delta':
        if (typeof event.response_id === 'string') this.audioResponseId = event.response_id;
        if (typeof event.delta === 'string') this.pendingAudioText = event.delta;
        break;
      case 'output_audio_buffer.cleared':
        this.pendingAudioText = undefined;
        break;
      case 'response.done':
        if (typeof event.response_id === 'string') this.openResponses.delete(event.response_id);
        break;
    }
  }

  private handleAudioDelta(event: RealtimeServerEvent): void {
    if (typeof event.audio !== 'string') return;
    if (typeof event.response_id === 'string') this.audioResponseId = event.response_id;
    // The JSON delta carries its own sentence text; a pending transcript delta is spent.
    this.pendingAudioText = undefined;
    if (this.audioListeners.size === 0) return;
    const fallback = this.outputAudio();
    const format = asAudioFormat(event.format) ?? fallback.format;
    const sampleRate = typeof event.sample_rate === 'number'
      ? event.sample_rate
      : format === fallback.format ? fallback.sampleRate : defaultSampleRate(format);
    const contentType = typeof event.content_type === 'string'
      ? event.content_type
      : contentTypeFor(format, sampleRate);
    const bytes = base64ToBytes(event.audio);
    this.emitAudio({
      responseId: this.audioResponseId,
      format,
      sampleRate,
      contentType,
      bytes,
      pcm: decodePcm(format, bytes),
      text: typeof event.text === 'string' ? event.text : undefined,
      transport: 'json',
    });
  }

  private handleBinaryAudio(bytes: Uint8Array): void {
    const text = this.pendingAudioText;
    this.pendingAudioText = undefined;
    if (this.audioListeners.size === 0) return;
    // The response's own format; the session echo only for frames that cannot be attributed.
    const { format, sampleRate } = (this.audioResponseId && this.responseAudio.get(this.audioResponseId))
      || this.outputAudio();
    this.emitAudio({
      responseId: this.audioResponseId,
      format,
      sampleRate,
      contentType: contentTypeFor(format, sampleRate),
      bytes,
      pcm: decodePcm(format, bytes),
      text,
      transport: 'binary',
    });
  }

  /** Output format/rate of binary frames: the server's echo wins over what this client requested. */
  private outputAudio(): { format: RealtimeAudioFormat; sampleRate: number } {
    const session = this.serverSession;
    const format = asAudioFormat(session?.output_audio_format) ?? this.requested.output ?? 'pcm16';
    if (format !== 'pcm16') return { format, sampleRate: 8000 };
    const rate = typeof session?.output_audio_sample_rate === 'number' && asAudioFormat(session?.output_audio_format)
      ? session.output_audio_sample_rate
      : this.requested.outputRate ?? 24000;
    return { format, sampleRate: rate };
  }

  /** The server fixes a response's output format when it creates the response — note it, like the server does. */
  private rememberOutputAudio(responseId: string): void {
    this.responseAudio.set(responseId, this.outputAudio());
    if (this.responseAudio.size > MAX_TRACKED_RESPONSES) {
      const oldest = this.responseAudio.keys().next().value;
      if (oldest !== undefined) this.responseAudio.delete(oldest);
    }
  }

  // ── Client events ───────────────────────────────────────────────────

  /** Send a raw client event. */
  send(event: Record<string, unknown>): void {
    this.assertOpen();
    this.socket.send(JSON.stringify(event));
  }

  private assertOpen(): void {
    if (this.socket.readyState !== OPEN) {
      throw new Error(
        this.closeInfo ? `Realtime socket is not open (closed: ${describeClose(this.closeInfo)})` : 'Realtime socket is not open',
      );
    }
  }

  /** Update session config (model, instructions, voice, audio formats, turn detection, first message…). */
  updateSession(session: RealtimeSessionUpdate): void {
    this.send({ type: 'session.update', session });
    if (session.output_audio_format !== undefined) this.requested.output = session.output_audio_format;
    if (session.output_audio_sample_rate !== undefined) this.requested.outputRate = session.output_audio_sample_rate;
  }

  /** Set `{{name}}` template variables (`session.update { variables }`). */
  setVariables(variables: RealtimeVariables): void {
    this.updateSession({ variables });
  }

  /** Append a user/system message to the conversation. */
  createItem(content: string, role: 'user' | 'system' | 'assistant' = 'user'): void {
    this.send({ type: 'conversation.item.create', item: { role, content } });
  }

  /**
   * Append an audio chunk (in the session's `input_audio_format`) as a base64
   * JSON `input_audio_buffer.append`. Strings are sent as-is (already base64);
   * bytes are encoded. {@link sendAudio} sends bytes as a binary frame instead
   * (less overhead).
   */
  appendAudio(audio: string | ArrayBuffer | ArrayBufferView): void {
    const base64 = typeof audio === 'string' ? audio : bytesToBase64(audioBytes(audio));
    this.send({ type: 'input_audio_buffer.append', audio: base64 });
  }

  /**
   * Stream input audio: raw bytes in the session's `input_audio_format`
   * (`pcm16` by default) go out as a binary WebSocket frame — no base64, no
   * JSON. Accepts Buffer / Uint8Array / ArrayBuffer / any typed-array view;
   * an `Int16Array` is sent as s16le and a `Float32Array` (Web Audio samples,
   * -1..1) is converted to `pcm16` first. A base64 string goes out through
   * {@link appendAudio}.
   */
  sendAudio(audio: string | ArrayBuffer | ArrayBufferView): void {
    if (typeof audio === 'string') {
      this.appendAudio(audio);
      return;
    }
    const bytes = audioBytes(audio);
    this.assertOpen();
    this.socket.send(bytes);
  }

  clearAudio(): void {
    this.send({ type: 'input_audio_buffer.clear' });
  }

  /** Transcribe the buffered audio and append it as a user turn (manual turn-taking, `turn_detection: null`). */
  commitAudio(): void {
    this.send({ type: 'input_audio_buffer.commit' });
  }

  /**
   * Ask the server to generate (and stream) the next assistant response.
   * `input` appends a user message first; `first_message: true` runs the
   * first-message logic now.
   */
  createResponse(overrides?: RealtimeResponseCreate): void {
    this.send({ type: 'response.create', response: overrides });
  }

  /** Speak the first message now (`response.create { first_message: true }`). */
  startFirstMessage(): void {
    this.createResponse({ first_message: true });
  }

  cancelResponse(): void {
    this.send({ type: 'response.cancel' });
  }

  /**
   * Report playback progress (`output_audio_buffer.played`). On an
   * interruption the server truncates the assistant's history entry to
   * roughly what was heard. Optional; send it every few hundred ms while
   * playing and once when playback is flushed.
   */
  reportPlayback(responseId: string, playedMs: number): void {
    this.send({
      type: 'output_audio_buffer.played',
      response_id: responseId,
      played_ms: Math.max(0, Math.round(playedMs)),
    });
  }

  /**
   * High-level helper: send a user message, wait for the full response.
   * Resolves with the final text (and base64 audio when TTS is configured).
   *
   * Only the response to THIS message counts. The message goes out as one
   * `response.create { input }`, so the server echoes the user item
   * (`conversation.item.created`) and starts answering it in the same step:
   * the first `response.created` after that echo is ours. Anything else — a
   * greeting that started (or is about to start) on connect, a voice turn —
   * is ignored, even when it begins after this call.
   *
   * Rejects when the response fails or is blocked, on a server error that can
   * only come from this request (audio and speech errors do not count: a
   * sentence whose speech failed still completes), when the socket closes or
   * {@link close} is called, and after `timeoutMs` (default 120000).
   */
  respond(content: string, options?: { timeoutMs?: number }): Promise<RealtimeRespondResult> {
    const timeoutMs = options?.timeoutMs ?? 120_000;
    // The server ignores an empty `input`: there would be no echo to wait for.
    if (!content) return Promise.reject(new Error('respond() needs a non-empty message'));
    const earlier = new Set(this.openResponses);
    const wanted = content.trim();
    let echoed = false;
    let ourId: string | null = null;
    const isOurs = (responseId: unknown) => ourId !== null && responseId === ourId;
    return new Promise((resolve, reject) => {
      let text = '';
      const audio: Uint8Array[] = [];
      const offs: Array<() => void> = [];
      const finish = (settle: () => void) => {
        clearTimeout(timer);
        offs.forEach((off) => off());
        settle();
      };
      const fail = (error: Error) => finish(() => reject(error));
      const timer = setTimeout(() => fail(new Error('Realtime response timed out')), timeoutMs);

      offs.push(this.on('conversation.item.created', (event) => {
        if (echoed) return;
        const item = event.item as { role?: unknown; content?: unknown } | undefined;
        if (item?.role !== 'user') return;
        if (typeof item.content === 'string' && item.content.trim() !== wanted) return;
        echoed = true;
      }));
      offs.push(this.on('response.created', (event) => {
        const id = (event.response as { id?: unknown } | undefined)?.id;
        if (typeof id !== 'string' || earlier.has(id)) return;
        if (echoed && ourId === null) ourId = id;
      }));
      offs.push(this.on('response.output_text.done', (event) => {
        if (isOurs(event.response_id)) text = String(event.text ?? '');
      }));
      offs.push(this.onAudio((chunk) => {
        if (isOurs(chunk.responseId)) audio.push(chunk.bytes);
      }));
      offs.push(this.on('response.done', (event) => {
        if (!isOurs(event.response_id)) return;
        if (event.status === 'completed' || event.status === 'cancelled') {
          finish(() => resolve({
            text,
            audio: audio.length > 0 ? bytesToBase64(concatBytes(audio)) : undefined,
            responseId: event.response_id,
          }));
        } else {
          fail(new Error(event.error?.message ?? `Response ${event.status ?? 'failed'}`));
        }
      }));
      offs.push(this.on('error', (event) => {
        if (UNRELATED_ERROR_CODES.has(String(event.error?.code))) return;
        fail(new Error(event.error?.message ?? 'Realtime error'));
      }));
      offs.push(this.watch(fail));

      try {
        this.createResponse({ input: content });
      } catch (error) {
        // Not open (any more): nothing was sent, so nothing to wait for.
        fail(error instanceof Error ? error : new Error(String(error)));
      }
    });
  }

  /** Reject `fail` when the socket goes away before the caller's work is done; returns the way to stop watching. */
  private watch(fail: (error: Error) => void): () => void {
    this.waiters.add(fail);
    return () => {
      this.waiters.delete(fail);
    };
  }

  /** Close the socket. A {@link respond} still pending rejects; {@link onClose} listeners hear the close itself. */
  close(): void {
    this.socket.close();
    this.failWaiters(new Error('Realtime connection closed'));
  }
}

